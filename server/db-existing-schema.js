// DB_BOOT_MODE=existing-schema: boot against a production database that already owns the platform tables.
// Nothing platform-owned is created, altered or seeded; the AI Board objects come only from the additive runner.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { analyzeMigrations, applyAdditive, AI_BOARD_BOOT_TABLES } from './ai-board/db/additive.js';

export const BOOT_MODES = ['legacy', 'existing-schema'];

/** Unset -> legacy. Unknown value throws: a typo must never fall back to a mode that writes to production. */
export function resolveBootMode(raw) {
  const v = String(raw ?? '').trim();
  if (!v) return 'legacy';
  if (!BOOT_MODES.includes(v)) throw new Error(`DB_BOOT_MODE=${JSON.stringify(v)} is not valid; use one of: ${BOOT_MODES.join(', ')} (or leave unset)`);
  return v;
}

const MANIFEST = fileURLToPath(new URL('./db-required-schema.json', import.meta.url));

/** Platform tables the app code uses: { table: [column] }. Generated by scripts/dump-required-schema.mjs. */
export function loadRequiredSchema(file = MANIFEST) {
  return JSON.parse(fs.readFileSync(file, 'utf8')).tables;
}

/** Tables created by the AI Board path, never platform-owned. */
export function aiBoardOwnedTables() {
  return new Set([...analyzeMigrations().newTables, 'schema_migrations', ...AI_BOARD_BOOT_TABLES, 'ai_private_previews', 'ai_preview_grants']);
}

/** Read-only: every required table/column exists in current_schema(). Returns the problem list. */
export async function findMissingSchema(d, required = loadRequiredSchema()) {
  const rows = await d.all(`SELECT table_name AS t, column_name AS c FROM information_schema.columns WHERE table_schema = current_schema()`);
  const have = new Map();
  for (const { t, c } of rows) (have.get(t) ?? have.set(t, new Set()).get(t)).add(c);
  const problems = [];
  for (const [table, cols] of Object.entries(required)) {
    const got = have.get(table);
    if (!got) { problems.push(`missing table ${table}`); continue; }
    const lack = cols.filter((c) => !got.has(c));
    if (lack.length) problems.push(`table ${table} lacks column(s): ${lack.join(', ')}`);
  }
  return problems;
}

/** Stops the boot with every missing object listed. */
export async function assertRequiredSchema(d, required) {
  const problems = await findMissingSchema(d, required);
  if (problems.length) {
    throw new Error(`DB_BOOT_MODE=existing-schema: the database does not match what the app needs; nothing was created.\n  ${problems.join('\n  ')}`);
  }
}

/** All AI Board receipts present -> read-only no-op. Otherwise the additive runner (needs ownership of `requests`). */
export async function ensureAiBoardAdditive(d, log = console) {
  const versions = analyzeMigrations().versions;
  const has = await d.get(`SELECT to_regclass('schema_migrations') IS NOT NULL AS ok`);
  const done = has?.ok
    ? new Set((await d.all(`SELECT version FROM schema_migrations WHERE scope = 'ai-board'`)).map((r) => r.version))
    : new Set();
  if (versions.every((v) => done.has(v))) return { applied: [], state: 'applied' };
  const client = await d.pool.connect();
  try {
    const res = await applyAdditive(client, { commit: true });
    log.log(`[db] existing-schema: AI Board additive migration applied (${res.applied.length} files)`);
    return res;
  } catch (error) {
    const detail = (error.problems ?? []).map((p) => (typeof p === 'string' ? p : `${p.level} ${p.check}: ${p.detail}`)).join('\n  ');
    throw new Error(`DB_BOOT_MODE=existing-schema: AI Board additive migration refused: ${error.message}${detail ? `\n  ${detail}` : ''}\n  Run server/scripts/ai-board-additive.mjs preflight/apply with the owner role instead.`);
  } finally {
    client.release();
  }
}
