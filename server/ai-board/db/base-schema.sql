CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
  username      TEXT   NOT NULL UNIQUE,
  display_name  TEXT   NOT NULL,
  password_hash TEXT   NOT NULL DEFAULT '',
  role          TEXT   NOT NULL DEFAULT 'student',
  enrolled_domain TEXT,
  email         TEXT,
  created_at    BIGINT NOT NULL DEFAULT 0,
  last_login    BIGINT
);
CREATE TABLE IF NOT EXISTS requests (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain      TEXT   NOT NULL,
  type        TEXT   NOT NULL DEFAULT 'other',
  title       TEXT   NOT NULL,
  detail      TEXT,
  student     TEXT   NOT NULL DEFAULT 'Ẩn danh',
  status      TEXT   NOT NULL DEFAULT 'pending',
  votes       BIGINT NOT NULL DEFAULT 1,
  admin_note  TEXT,
  created_at  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL,
  attachments TEXT
);
CREATE INDEX IF NOT EXISTS idx_requests_domain ON requests(domain, votes DESC, created_at DESC);
CREATE TABLE IF NOT EXISTS request_messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id  BIGINT NOT NULL,
  role        TEXT   NOT NULL,
  author_name TEXT,
  body        TEXT   NOT NULL,
  attachments TEXT,
  created_at  BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_request_messages ON request_messages(request_id, created_at);
CREATE TABLE IF NOT EXISTS skill_proposals (
  id            BIGSERIAL PRIMARY KEY,
  origin        TEXT   NOT NULL,
  domain        TEXT,
  gate_reached  DOUBLE PRECISION NOT NULL,
  outcome       TEXT,
  request_ids   TEXT,
  template_key  TEXT,
  budget_json   TEXT,
  pr_url        TEXT,
  created_at    BIGINT NOT NULL,
  updated_at    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_skill_proposals_template ON skill_proposals(template_key, created_at DESC);
CREATE TABLE IF NOT EXISTS gate_trace (
  id                   BIGSERIAL PRIMARY KEY,
  skill_proposal_id    BIGINT NOT NULL,
  gate                 DOUBLE PRECISION NOT NULL,
  model                TEXT,
  prompt               TEXT,
  raw_response         TEXT,
  prompt_eval_count    BIGINT,
  eval_count           BIGINT,
  prompt_eval_duration BIGINT,
  eval_duration        BIGINT,
  created_at           BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_gate_trace_proposal ON gate_trace(skill_proposal_id, created_at);
