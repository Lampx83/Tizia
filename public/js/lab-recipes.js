export function getRecipeById(id) {
  return RECIPES.find(r => r.id === id) || RECIPES[0];
}

export function getRecipeFromUrl() {
  const p = new URLSearchParams(location.search);
  const id = p.get('recipe');
  if (id) return getRecipeById(id);
  return null;
}
