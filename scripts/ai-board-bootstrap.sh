#!/usr/bin/env bash
# Clean-host bootstrap for the dev stack + AI Board (Linux, or Git Bash on Windows with Docker Desktop).
# Preflight, create runner token, write KVM_GID and the resource profile to ai-board-host.env (not .env).
# DEV=1 in .env selects the laptop profile (dev policy, small CPU/RAM limits); DEV=0 or unset selects the server profile (large).
# --build-guest: build the Gate 5 guest, push to image-registry, optional warm cache, pin digest in the dev policy.
# Usage (repo root):
#   scripts/ai-board-bootstrap.sh
#   scripts/ai-board-bootstrap.sh --build-guest [--warm-dir DIR]   # DIR holds docker-data.tar.gz from scripts/warm-guest.mjs
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

COMPOSE=(docker compose -f docker-compose.dev.local.yml)
# AI_BOARD_COMPOSE_OVERLAYS="a.yml b.yml": extra local override files merged after dev.local.yml (not tracked)
for overlay in ${AI_BOARD_COMPOSE_OVERLAYS:-}; do COMPOSE+=(-f "$overlay"); done
TOKEN=ai-board/sandbox-runner/secrets/runner-token
HOST_ENV=ai-board-host.env
REGISTRY=localhost:5000
GUEST_TAG=tizia-gate5-guest:dev

build_guest=0
start_stack=0
warm_dir=
while [ $# -gt 0 ]; do
  case $1 in
    --build-guest) build_guest=1 ;;
    --up) start_stack=1 ;;
    --warm-dir) warm_dir=${2:?--warm-dir needs a directory}; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

errors=()
err() { errors+=("$1"); }

command -v docker >/dev/null 2>&1 || err "docker not found in PATH"
if command -v docker >/dev/null 2>&1; then
  docker info >/dev/null 2>&1 || err "docker daemon not reachable (start Docker Desktop / dockerd)"
  docker compose version >/dev/null 2>&1 || err "docker compose v2 plugin missing"
fi

[ -f .env ] || err ".env missing: create it from .env.example and set POSTGRES_PASSWORD and the AI Board keys (values never printed here)"

kvm_gid=
if [ "$(uname -s)" = Linux ]; then
  if [ ! -c /dev/kvm ]; then
    err "/dev/kvm missing: enable VT-x/AMD-V in BIOS and load the kvm module (sandbox-runner needs it)"
  elif [ ! -r /dev/kvm ] || [ ! -w /dev/kvm ]; then
    err "/dev/kvm not readable+writable by $(id -un): add this user to the group that owns /dev/kvm"
  else
    kvm_gid=$(stat -c %g /dev/kvm)
  fi
else
  echo "note: not a Linux host; /dev/kvm is checked inside the Docker VM, sandbox-runner readiness will show if it is missing" >&2
fi

if command -v openssl >/dev/null 2>&1; then
  if [ -d "$TOKEN" ]; then
    rmdir "$TOKEN" 2>/dev/null || err "$TOKEN is a non-empty directory; remove it and rerun"
  fi
  if [ ! -s "$TOKEN" ] && [ ! -d "$TOKEN" ]; then
    mkdir -p "$(dirname "$TOKEN")"
    openssl rand -hex 32 > "$TOKEN"
    chmod 644 "$TOKEN"  # runner and app containers read it as uid 1000, not the host owner
    echo "created $TOKEN (64 hex chars, mode 644)" >&2
  fi
  if [ -f "$TOKEN" ] && [ "$(wc -c < "$TOKEN")" -lt 33 ]; then
    err "$TOKEN is shorter than 32 characters: delete it and rerun (runner refuses short tokens)"
  fi
else
  err "openssl not found: needed to create $TOKEN"
fi

dev_flag=
[ -f .env ] && dev_flag=$(sed -n 's/^DEV=//p' .env | tail -n 1 | tr -d '\r "'"'")
if [ "$dev_flag" = 1 ]; then
  profile=dev; limits='WORKER_CPUS=2 WORKER_MEM=4g RUNNER_CPUS=6 RUNNER_MEM=3g'
else
  profile=large; limits='WORKER_CPUS=8 WORKER_MEM=16g RUNNER_CPUS=10 RUNNER_MEM=6g'
fi
POLICY=ai-board/sandbox-runner/sandbox-policy.$profile.yaml
[ -n "$kvm_gid" ] || { [ -f "$HOST_ENV" ] && kvm_gid=$(sed -n 's/^KVM_GID=//p' "$HOST_ENV" | tail -n 1); } || true
{
  printf '# generated by scripts/ai-board-bootstrap.sh from DEV in .env; host-specific, not tracked\n'
  [ -z "$kvm_gid" ] || printf 'KVM_GID=%s\n' "$kvm_gid"
  printf 'RESOURCE_PROFILE=%s\n' "$profile"
  printf '%s\n' $limits
} > "$HOST_ENV"
env_args=()
[ -f .env ] && env_args+=(--env-file .env)
env_args+=(--env-file "$HOST_ENV")
echo "resource profile: $profile (DEV=${dev_flag:-unset})" >&2

if [ ${#errors[@]} -eq 0 ]; then
  if ! config_err=$("${COMPOSE[@]}" "${env_args[@]}" config -q 2>&1); then
    err "compose config invalid: $(printf '%s' "$config_err" | tail -n 1)"
  fi
fi

if [ ${#errors[@]} -gt 0 ]; then
  echo "ai-board-bootstrap: ${#errors[@]} problem(s):" >&2
  printf '  - %s\n' "${errors[@]}" >&2
  exit 1
fi

if [ "$start_stack" -eq 1 ]; then
  "${COMPOSE[@]}" "${env_args[@]}" up -d --build
  exit 0
fi

if [ "$build_guest" -eq 0 ]; then
  echo "ready. Start: docker compose -f docker-compose.dev.local.yml ${env_args[*]} up -d --build"
  echo "Gate 5 guest still needs: scripts/ai-board-bootstrap.sh --build-guest"
  exit 0
fi

command -v node >/dev/null 2>&1 || { echo "node required for --build-guest (guest-inputs.mjs)" >&2; exit 1; }
if [ -n "$warm_dir" ] && [ ! -f "$warm_dir/docker-data.tar.gz" ]; then
  echo "$warm_dir/docker-data.tar.gz not found (produce it with scripts/warm-guest.mjs inside a running runner)" >&2
  exit 1
fi

"${COMPOSE[@]}" "${env_args[@]}" up -d image-registry
for _ in $(seq 30); do
  curl -fsS "http://127.0.0.1:5000/v2/" >/dev/null 2>&1 && break
  sleep 1
done
curl -fsS "http://127.0.0.1:5000/v2/" >/dev/null || { echo "image-registry not answering on 127.0.0.1:5000" >&2; exit 1; }

docker build -f ai-board/sandbox-runner/guest/Dockerfile -t "$GUEST_TAG" .

if [ -n "$warm_dir" ]; then
  ref=$REGISTRY/gate5:warm
  docker build -f ai-board/sandbox-runner/guest/Dockerfile.warm --build-arg BASE="$GUEST_TAG" -t "$ref" "$warm_dir"
else
  ref=$REGISTRY/gate5:cold
  docker tag "$GUEST_TAG" "$ref"
fi

push_out=$(docker push "$ref" 2>&1) || { printf '%s\n' "$push_out" >&2; exit 1; }
printf '%s\n' "$push_out"
digest=$(printf '%s\n' "$push_out" | sed -n 's/.*digest: \(sha256:[0-9a-f]\{64\}\).*/\1/p' | tail -n 1)
[ -n "$digest" ] || { echo "push did not report a digest" >&2; exit 1; }

node ai-board/sandbox-runner/scripts/guest-inputs.mjs pin "$POLICY" "$digest"
echo "pinned $digest in $POLICY (tracked file: review git diff before committing)"

"${COMPOSE[@]}" "${env_args[@]}" up -d --build --force-recreate sandbox-runner
echo "sandbox-runner restarted with the new pin; check: docker compose ... logs sandbox-runner"
