#!/usr/bin/env bash
# Optional preflight for the dev stack + AI Board (Linux, or Git Bash on Windows with Docker Desktop).
# `docker compose -f docker-compose.dev.local.yml up -d --build` alone builds and starts everything: compose services
# create the runner token and build the Gate 5 guest, and the runner entrypoint reads the /dev/kvm group.
# This script only checks the host and writes the resource profile to ai-board-host.env.
# DEV=0 in the app settings file selects the server profile (large); any other value or unset selects the small dev profile.
# Usage (repo root):
#   scripts/ai-board-bootstrap.sh          # preflight + profile file
#   scripts/ai-board-bootstrap.sh --up     # same, then docker compose up -d --build
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

COMPOSE=(docker compose -f docker-compose.dev.local.yml)
# AI_BOARD_COMPOSE_OVERLAYS="a.yml b.yml": extra local override files merged after dev.local.yml (not tracked)
for overlay in ${AI_BOARD_COMPOSE_OVERLAYS:-}; do COMPOSE+=(-f "$overlay"); done
HOST_ENV=ai-board-host.env

start_stack=0
while [ $# -gt 0 ]; do
  case $1 in
    --up) start_stack=1 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

errors=()
err() { errors+=("$1"); }

command -v docker >/dev/null 2>&1 || err "docker not found in PATH"
if command -v docker >/dev/null 2>&1; then
  docker info >/dev/null 2>&1 || err "docker daemon not reachable (start Docker Desktop / dockerd)"
  docker compose version >/dev/null 2>&1 || err "docker compose v2 plugin missing"
fi

[ -f .env ] || err ".env missing: create it from .env.example and set POSTGRES_PASSWORD and the AI Board keys (values never printed here)"

if [ "$(uname -s)" = Linux ]; then
  [ -c /dev/kvm ] || err "/dev/kvm missing: enable VT-x/AMD-V in BIOS and load the kvm module (sandbox-runner needs it)"
else
  echo "note: not a Linux host; /dev/kvm is checked inside the Docker VM, sandbox-runner readiness will show if it is missing" >&2
fi

# Only an explicit DEV=0 selects large; unset or any other value falls back to the small dev profile.
profile_for() {
  if [ "$1" = 0 ]; then
    echo "large WORKER_CPUS=8 WORKER_MEM=16g RUNNER_CPUS=10 RUNNER_MEM=6g"
  else
    echo "dev WORKER_CPUS=2 WORKER_MEM=4g RUNNER_CPUS=6 RUNNER_MEM=3g"
  fi
}

dev_flag=
[ -f .env ] && dev_flag=$(sed -n 's/^DEV=//p' .env | tail -n 1 | tr -d '\r "'"'")
resolved=$(profile_for "$dev_flag")
profile=${resolved%% *}
limits=${resolved#* }
{
  printf '# generated by scripts/ai-board-bootstrap.sh from DEV in .env; host-specific, not tracked\n'
  printf 'RESOURCE_PROFILE=%s\n' "$profile"
  printf '%s\n' $limits
} > "$HOST_ENV"
env_args=()
[ -f .env ] && env_args+=(--env-file .env)
env_args+=(--env-file "$HOST_ENV")
echo "resource profile: $profile (DEV=${dev_flag:-unset})" >&2

if [ ${#errors[@]} -eq 0 ]; then
  if ! config_err=$("${COMPOSE[@]}" "${env_args[@]}" config -q 2>&1); then
    err "compose config invalid: $(printf '%s' "$config_err" | tail -n 1)"
  fi
fi

if [ ${#errors[@]} -gt 0 ]; then
  echo "ai-board-bootstrap: ${#errors[@]} problem(s):" >&2
  printf '  - %s\n' "${errors[@]}" >&2
  exit 1
fi

if [ "$start_stack" -eq 1 ]; then
  "${COMPOSE[@]}" "${env_args[@]}" up -d --build
  exit 0
fi

echo "ready. Start: docker compose -f docker-compose.dev.local.yml ${env_args[*]} up -d --build"
